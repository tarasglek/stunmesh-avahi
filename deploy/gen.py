#!/usr/bin/env -S uv run --script
# /// script
# dependencies = ["pyyaml"]
# ///
# Render every node's wgmesh/stunmesh configs and wgmesh.hosts next to mesh.yaml.
#   ./gen.py CONFIG_DIR/mesh.yaml
import sys
from pathlib import Path

import yaml

if len(sys.argv) != 2:
    sys.exit(f"usage: {sys.argv[0]} CONFIG_DIR/mesh.yaml")
MESH = Path(sys.argv[1])
DIR = MESH.parent
# Every node needs its own WireGuard port, set in mesh.yaml so it never moves.
# Nodes sharing a NAT on one port collide: the second gets a random public port
# per destination, so the endpoint STUN publishes is wrong and hole punching
# fails without router port-forward rules. With unique ports, plain masquerade
# keeps each node's port toward everyone. The range sits just below Linux's
# ephemeral ports (32768+), so ordinary client traffic doesn't borrow them.
PORT_MIN, PORT_MAX = 32000, 32767
DOMAIN = "mesh.internal"
GENERATED = "# Generated by gen.py from ../mesh.yaml; edit that instead.\n"

nodes = yaml.safe_load(MESH.read_text())["nodes"]

ports = [n["port"] for n in nodes.values() if "port" in n]
for name, n in nodes.items():
    if "port" not in n:
        # count down from the top, so new nodes never reuse a port
        sys.exit(f"{name}: no port; add \"port: {min(ports, default=PORT_MAX + 1) - 1}\"")
    if not PORT_MIN <= n["port"] <= PORT_MAX:
        sys.exit(f"{name}: port {n['port']} outside {PORT_MIN}-{PORT_MAX}")
for key in ("port", "ip"):
    seen = [n[key] for n in nodes.values()]
    dup = {v for v in seen if seen.count(v) > 1}
    if dup:
        sys.exit(f"duplicate {key}: {', '.join(map(str, dup))}")


def wg_conf(ip, port, peers):
    out = f"""{GENERATED}# WireGuard interface for the stunmesh mesh, installed to
# /etc/wireguard/wgmesh.conf by install.sh. The private key stays on the
# node in /etc/wireguard/wgmesh.key; stunmesh-go sets peer endpoints.
[Interface]
Address = {ip}/24
ListenPort = {port}
PostUp = wg set %i private-key /etc/wireguard/wgmesh.key
"""
    for p in peers.values():
        out += f"""
[Peer]
PublicKey = {p['pubkey']}
AllowedIPs = {p['ip']}/32
PersistentKeepalive = 25
"""
    return out


def wg_uci(ip, port, peers):
    out = f"""{GENERATED}# uci batch for the wgmesh interface on this OpenWrt node, applied by
# openwrt/setup.sh. The private key stays on the node in
# /etc/wireguard/wgmesh.key; stunmesh-go sets peer endpoints.
set network.wgmesh=interface
set network.wgmesh.proto='wireguard'
set network.wgmesh.listen_port='{port}'
delete network.wgmesh.addresses
add_list network.wgmesh.addresses='{ip}/24'
"""
    for name, p in peers.items():
        s = "network.wgmesh_" + name.replace("-", "_")
        out += f"""set {s}=wireguard_wgmesh
set {s}.description='{name}'
set {s}.public_key='{p['pubkey']}'
delete {s}.allowed_ips
add_list {s}.allowed_ips='{p['ip']}/32'
set {s}.persistent_keepalive='25'
"""
    return out + f"""# Mesh traffic is trusted like LAN (zone 0 is lan on this node).
del_list firewall.@zone[0].network='wgmesh'
add_list firewall.@zone[0].network='wgmesh'
# WireGuard in from any uplink (home Wi-Fi and LTE are both in zone wan).
set firewall.wgmesh_in=rule
set firewall.wgmesh_in.name='Allow-wgmesh'
set firewall.wgmesh_in.src='wan'
set firewall.wgmesh_in.proto='udp'
set firewall.wgmesh_in.dest_port='{port}'
set firewall.wgmesh_in.target='ACCEPT'
# mDNS multicast only, so stunmesh-avahi sees LAN peers on home Wi-Fi.
set firewall.mdns_in=rule
set firewall.mdns_in.name='Allow-mDNS'
set firewall.mdns_in.src='wan'
set firewall.mdns_in.proto='udp'
set firewall.mdns_in.dest_ip='224.0.0.251'
set firewall.mdns_in.dest_port='5353'
set firewall.mdns_in.target='ACCEPT'
"""


def stunmesh_yaml(peers):
    out = f"""{GENERATED}# stunmesh-go config, installed to /etc/stunmesh/config.yaml by install.sh
---
refresh_interval: "1m"
log:
  level: "info"
interfaces:
  wgmesh:
    peers:
"""
    for name, p in peers.items():
        out += f"""      "{name}":
        public_key: "{p['pubkey']}"
        plugin: avahi-then-dht
"""
    return out + """stun:
  addresses: ["stun.l.google.com:19302", "stun.cloudflare.com:3478"]
plugins:
  # LAN address via avahi when the peer shares our public IP, else OpenDHT.
  # OpenDHT needs no account or token, so this file holds no secrets.
  avahi-then-dht:
    type: shell
    command: /usr/local/bin/stunmesh-avahi
    args:
      - -dev=wgmesh
      - --
      - /usr/local/bin/stunmesh-opendht-shell
      - -endpoint
      - https://dhtproxy2.jami.net
      - -endpoint
      - https://dhtproxy3.jami.net
    dedup: false # values expire after 10 min; every refresh must republish
"""


for name, n in nodes.items():
    peers = {k: v for k, v in nodes.items() if k != name and v.get("pubkey")}
    d = DIR / name
    d.mkdir(exist_ok=True)
    if n.get("openwrt"):
        (d / "wgmesh.uci").write_text(wg_uci(n["ip"], n["port"], peers))
    else:
        (d / "wgmesh.conf").write_text(wg_conf(n["ip"], n["port"], peers))
    (d / "config.yaml").write_text(stunmesh_yaml(peers))

(DIR / "wgmesh.hosts").write_text(
    "".join(f"{n['ip']} {name}.{DOMAIN}\n" for name, n in nodes.items())
)
